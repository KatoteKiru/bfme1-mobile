#!/usr/bin/env python3
"""E1-56: "key opens a block" table for the engine's BFME INI skipper, from schema/opensage_schema.json.

Output (TSV, no EA data -- only INI schema names from OpenSAGE sources):
  @top     <BlockName>   <table id>          top-level block -> its field table
  @topline <BlockName>                       top-level definition on one line (no End), e.g. LODPreset
  @value   <Field>                           name that is a value field in some table (never an opener
                                             when the table is unknown)
  @module  <module table> <ModuleType> <table id>   module type in a module parse table -> its field table
  <table id> <Field>  <child table id>       field that opens a nested block with its own table
  <table id> <Field>  @module:<module table> field that opens a module block (type = next token)
  <table id> <Field>  <child table id> <n>   ... only when the line has at least n value tokens (else a value)
  <table id> <Field>  @arbitrary             block of free key = value lines (no nested blocks)
  <table id> <Field>  @unknown               opener seen in the data (report.json unknown_fields_as_blocks),
                                             its own fields unknown to the schema
Usage: gen_block_openers.py [schema.json [out-all/report.json]] > formats/ini/bfme1-block-openers.tsv
"""
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
s = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'opensage_schema.json')))
out = ['# generated by tools/datacheck/schema/gen_block_openers.py from opensage_schema.json (revision %s)'
       % s.get('revision', '?')]
for name, b in sorted(s['top_level'].items()):
    if b.get('table'):
        out.append(f'@top\t{name}\t{b["table"]}')
    elif b.get('kind') == 'value':
        out.append(f'@topline\t{name}')
values = sorted({f for t in s['tables'].values() for f, d in t.get('fields', {}).items() if d.get('kind') == 'value'})
openers = {f.lower() for t in s['tables'].values() for f, d in t.get('fields', {}).items() if d.get('kind') in ('block', 'module')}
for f in values:
    if f.lower() in openers:
        out.append(f'@value\t{f}')
for mt, types in sorted(s['module_tables'].items()):
    for typ, d in sorted(types.items()):
        if d.get('table'):
            out.append(f'@module\t{mt}\t{typ}\t{d["table"]}')
for tid, t in sorted(s['tables'].items()):
    for f, d in sorted(t.get('fields', {}).items()):
        if d.get('kind') == 'block' and d.get('table'):
            mv = f'\t{d["min_values"]}' if d.get('min_values') else ''
            out.append(f'{tid}\t{f}\t{d["table"]}{mv}')
        elif d.get('kind') == 'block' and d.get('arbitrary'):
            out.append(f'{tid}\t{f}\t@arbitrary')
        elif d.get('kind') == 'module' and d.get('module_table'):
            out.append(f'{tid}\t{f}\t@module:{d["module_table"]}')
if len(sys.argv) > 2:
    by_class = {}
    for tid, t in s['tables'].items():
        by_class.setdefault(t['class'], []).append(tid)
    rep = json.load(open(sys.argv[2]))
    for u in rep['ini'].get('unknown_fields_as_blocks', []):
        cls, field = u['key'].split('.', 1)
        for tid in sorted(by_class.get(cls, [])):
            out.append(f'{tid}\t{field}\t@unknown')
print('\n'.join(out))
